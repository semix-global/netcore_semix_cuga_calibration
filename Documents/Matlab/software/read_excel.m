% 自定义数据提示的更新函数
function txt = myupdatefcn(~, event_obj)
    % 获取当前位置的句柄
    pos = get(event_obj, 'Position');
    target = get(event_obj, 'Target');
    
    % 获取曲线的名称
    plotName = get(target, 'DisplayName');
    
    % 构建显示文本
    txt = {['X: ', num2str(pos(1))], ...
           ['Y: ', num2str(pos(2))], ...
           ['Name: ', plotName]};
end

% 复选框回调函数，用于切换线条的可见性
function toggleLineTable(~, event, h)
    % 获取被编辑的行索引
    colIndex = event.Indices(1);
    if event.NewData
        h(colIndex).Visible = 'on';  % 显示对应的线条
    else
        h(colIndex).Visible = 'off';  % 隐藏对应的线条
    end
end

function color = GetColor(cmap, position, range)
    % 获取颜色映射方案的总长度
    nColors = size(cmap, 1);
    
    % 如果 position 是 NaN，返回透明色
    if isnan(position)
        color = [1, 1, 1, 0];  % 返回 RGBA 格式的透明色
        return;
    end
    
    % 如果 range 的最小值等于最大值，返回颜色映射的第一个颜色
    if range(1) == range(2)
        color = cmap(1, :);
        return;
    end
    
    % 标准化 position 到 [0, 1] 范围
    normalizedPosition = (position - range(1)) / (range(2) - range(1));
    
    % 限制 normalizedPosition 在 [0, 1] 范围内
    normalizedPosition = max(0, min(1, normalizedPosition));
    
    % 计算颜色的索引
    index = round((nColors - 1) * normalizedPosition) + 1;  % MATLAB 索引从 1 开始
    
    % 返回对应的颜色
    color = cmap(index, :);
end


