function toggleLineTable(src, event, h)
    % 切换线条的可见性
    colIndex = event.Indices(1); % 获取被编辑的行索引
    if event.NewData
        h(colIndex).Visible = 'on';
    else
        h(colIndex).Visible = 'off';
    end
end