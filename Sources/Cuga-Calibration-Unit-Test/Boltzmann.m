% 创建图例文本
eq_text = sprintf('y = %.6f + (%.6f-%.6f)/[1+e^{((x-%.6f)/%.6f)}]', ...
    beta(2), beta(1), beta(2), beta(3), beta(4));
legend_text = sprintf('%s\nR² = %.6f', eq_text, R2);

