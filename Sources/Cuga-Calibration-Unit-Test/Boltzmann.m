% Boltzmann拟合
boltzmann = @(b, x) b(2) + (b(1) - b(2)) ./ (1 + exp((x - b(3)) / b(4)));

% 智能确定初始参数
A1_guess = max(y); % 上限（y的最大值）
A2_guess = min(y); % 下限（y的最小值）

% 自动计算中点x0：基于数据分布
% 找到y值接近(A1_guess + A2_guess) / 2 的点
mid_y = (A1_guess + A2_guess) / 2;
[~, idx] = min(abs(y - mid_y));
x0_guess = x(idx); % 取最接近中值的x点

% 自动计算斜率dx：基于数据分布的特征
% 使用线性回归估计变化率
dy = diff(y);
dx = diff(x);
slopes = dy ./ dx; % 每个区间的斜率
dx_guess = median(abs(slopes)); % 使用中值作为初始斜率估计

% 确保dx不为0或太小
if dx_guess < 0.1
    dx_guess = 0.5; % 设置最小阈值
end

beta0 = [A1_guess, A2_guess, x(length(x) / 2), 1];
fprintf('Guess Param: A1=%.6f, A2=%.6f, x0=%.6f, dx=%.6f\n', beta0);

% 拟合
beta = lsqcurvefit(boltzmann, beta0, x, y);

% 计算R²
y_fit = boltzmann(beta, x); % 在原始x点处的拟合值
R2 = 1 - sum((y - y_fit) .^ 2) / sum((y - mean(y)) .^ 2);

% 绘图
